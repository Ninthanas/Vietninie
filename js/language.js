const ChineseScriptEngine = {
  getMode() {
    // 'simplified' (简体 🇨🇳) | 'traditional' (繁體 🇹🇼) | 'both' (简+繁)
    return localStorage.getItem('vietninie_zh_script') || 'both';
  },

  setMode(mode) {
    const valid = ['simplified', 'traditional', 'both'].includes(mode) ? mode : 'both';
    localStorage.setItem('vietninie_zh_script', valid);
    this.updateButtonUI();
    if (window.LanguageManager) {
      window.LanguageManager.applyTranslations();
    }
    window.dispatchEvent(new CustomEvent('sentruc:lang-changed', { detail: { script: valid } }));
  },

  cycleMode() {
    const order = ['simplified', 'traditional', 'both'];
    const curr = this.getMode();
    const next = order[(order.indexOf(curr) + 1) % order.length];
    this.setMode(next);
    const labels = {
      simplified: '🇨🇳 Đã chuyển chữ Hán sang: Giản Thể (简体 - Đại lục)',
      traditional: '🇹🇼 Đã chuyển chữ Hán sang: Phồn Thể (繁體 - Đài Loan)',
      both: '🇨🇳/🇹🇼 Đã bật hiển thị song song: Giản Thể + Phồn Thể (简 + 繁)'
    };
    if (window.AppUI) window.AppUI.showToast(labels[next]);
  },

  updateButtonUI() {
    const btn = document.getElementById('scriptSwitchBtn');
    if (!btn) return;
    const mode = this.getMode();
    const badgeMap = {
      simplified: '简 🇨🇳',
      traditional: '繁 🇹🇼',
      both: '简·繁'
    };
    btn.innerHTML = `<span>${badgeMap[mode]}</span>`;
    btn.setAttribute('title', 'Chuyển đổi Chữ Giản Thể (Đại lục) / Phồn Thể (Đài Loan) / Song song');
  },

  toTraditional(str = '') {
    if (!str) return '';
    return Array.from(String(str)).map(ch => S2T_CHAR_MAP[ch] || ch).join('');
  },

  formatText(str = '') {
    if (!str) return '';
    const mode = this.getMode();
    if (mode === 'simplified') return str;
    const trad = this.toTraditional(str);
    if (mode === 'traditional') return trad;
    if (trad !== str && str.length <= 8) {
      return `${str} <span style="font-weight:600; color:var(--brand-indigo); font-size:0.86em;">(繁: ${trad})</span>`;
    }
    return str;
  },

  getScriptPair(str = '') {
    const simp = String(str || '');
    const trad = this.toTraditional(simp);
    return { simp, trad, differs: simp !== trad };
  },

  getTaiwanComparison(wordOrMeaning = '') {
    for (const [k, val] of Object.entries(TAIWAN_PHRASE_EQUIVALENTS)) {
      if (wordOrMeaning.includes(k)) return { mainland: k, ...val };
    }
    return null;
  }
};

