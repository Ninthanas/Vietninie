const LanguageManager = {
  getNativeLang() {
    return localStorage.getItem('sentruc_native_lang') || 'vi';
  },

  setNativeLang(lang) {
    const valid = lang === 'zh' ? 'zh' : 'vi';
    localStorage.setItem('sentruc_native_lang', valid);
    document.documentElement.lang = valid;
    this.applyTranslations();
    window.dispatchEvent(new CustomEvent('sentruc:lang-changed', { detail: { lang: valid } }));
  },

  toggleLanguage() {
    const current = this.getNativeLang();
    this.setNativeLang(current === 'vi' ? 'zh' : 'vi');
  },

  getLearningLang() {
    return this.getNativeLang() === 'vi' ? 'zh' : 'vi';
  },

  t(key, fallback = '') {
    const lang = this.getNativeLang();
    let val = (translations[lang] && translations[lang][key]) || fallback || key;
    if (lang === 'zh' && ChineseScriptEngine.getMode() === 'traditional') {
      val = ChineseScriptEngine.toTraditional(val);
    }
    return val;
  },

  applyTranslations() {
    const lang = this.getNativeLang();
    document.documentElement.lang = lang;
    ChineseScriptEngine.updateButtonUI();

    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      const val = this.t(key);
      if (val) el.innerHTML = val;
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const key = el.getAttribute('data-i18n-placeholder');
      const val = this.t(key);
      if (val) el.setAttribute('placeholder', val);
    });
  }
};

window.ChineseScriptEngine = ChineseScriptEngine;
window.DeepWordInsightEngine = DeepWordInsightEngine;
window.LanguageManager = LanguageManager;
window.translations = translations;

